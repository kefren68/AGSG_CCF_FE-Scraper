    def _write_ra_game_cfg(self, sys_dir, stem):
        """Create RetroArch game override cfg that enables the bezel overlay for this game.
        Output: <sys_dir>/bezels/copy inside retroarch/config/_<system_name>/<stem>.cfg
        """
        out_dir = sys_dir / "bezels" / "copy inside retroarch" / "config" / f"_{sys_dir.name}"
        out_dir.mkdir(parents=True, exist_ok=True)
        cfg_path = out_dir / f"{stem}.cfg"
        if self.overwrite or not cfg_path.exists():
            overlay_cfg = f"{self.overlay_base_path}/{sys_dir.name}/bezels/{stem}.cfg"
            cfg_path.write_text(
                f'input_overlay = "{overlay_cfg}"\n'
                f'input_overlay_auto_scale = "true"\n'
            )

    def _ra_login(self):
        """Login to RetroAchievements and cache the session token. Returns token or None."""
        if self._ra_token is not None:
            return self._ra_token if self._ra_token else None
        try:
            r = self.client.session.post(
                "https://retroachievements.org/dorequest.php",
                params={"r": "login2", "u": self.ra_user, "p": self.ra_key},
                timeout=10,
            )
            if self.verbose:
                print(f"      [verbose] RA login HTTP {r.status_code}: {r.text[:120]}", file=sys.stderr)
            if r.status_code == 200:
                data = r.json()
                if data.get("Success"):
                    self._ra_token = data.get("Token")
                    return self._ra_token
                else:
                    print(f"  [RA] Login error: {data.get('Error', 'unknown')}")
            else:
                print(f"  [RA] Login HTTP {r.status_code}")
        except Exception as e:
            print(f"  [RA] Login exception: {e}")
        self._ra_token = False  # mark as failed so we don't retry every ROM
        return None

    def _ra_game_has_achievements(self, game_id):
        """Return True if game_id has at least one achievement on RA (via r=patch)."""
        if game_id in self._ra_game_cache:
            return self._ra_game_cache[game_id]
        token = self._ra_login()
        if not token:
            self._ra_game_cache[game_id] = False
            return False
        try:
            r2 = self.client.session.get(
                "https://retroachievements.org/dorequest.php",
                params={"r": "patch", "u": self.ra_user, "t": token, "g": game_id},
                timeout=10,
            )
            if r2.status_code == 200:
                achievements = r2.json().get("PatchData", {}).get("Achievements", [])
                result = len(achievements) > 0
                self._ra_game_cache[game_id] = result
                return result
        except Exception as e:
            print(f"      [RA] patch lookup error: {e}")
        self._ra_game_cache[game_id] = False
        return False

    def _query_ra_cheevos(self, md5, ra_console_id=None):
        """Return True/False/None for RetroAchievements cheevos presence.

        Return values:
          True  — RA recognises the ROM and it has achievements.
          False — RA recognises the ROM (GameID > 0) but it has 0 achievements.
          None  — RA does not recognise this ROM hash (GameID=0), credentials
                  missing/failed, or a network error occurred.  The caller
                  falls back to ScreenScraper's retroachievement field.

        Returning None for GameID=0 is intentional: an unknown hash just means
        RA does not have a matching entry for this ROM version — it does NOT
        mean the game has no achievements.  ScreenScraper may still know.

        ra_console_id: optional RA console ID (see _SS_TO_RA_CONSOLE_ID).
          When provided, the gameid query is first tried without the console ID
          (global search), and if that returns 0 it is retried with c=CONSOLE_ID.
          This is needed for Arcade systems (CPS1/2/3, Neo Geo) whose hashes are
          stored under RA's Arcade console (27) and may not surface in the global
          hash lookup.
        """
        if not self.ra_user or not self.ra_key or not md5:
            return None  # not configured — caller keeps ScreenScraper value
        md5u = md5.upper()
        if md5u in self._ra_cache:
            return self._ra_cache[md5u]
        token = self._ra_login()
        if not token:
            return None

        # We try up to two queries:
        #   pass 1 — global search (no console ID)
        #   pass 2 — console-specific search (only when ra_console_id given and pass 1 missed)
        queries = [{"r": "gameid", "m": md5u, "u": self.ra_user, "t": token}]
        if ra_console_id is not None:
            queries.append({"r": "gameid", "m": md5u, "u": self.ra_user, "t": token,
                            "c": ra_console_id})

        for i, params in enumerate(queries):
            try:
                r = self.client.session.get(
                    "https://retroachievements.org/dorequest.php",
                    params=params,
                    timeout=10,
                )
                if r.status_code == 200:
                    data = r.json()
                    game_id = int(data.get("GameID", 0))
                    if game_id <= 0:
                        if i == 0 and ra_console_id is not None:
                            if self.verbose:
                                print(f"      [verbose] RA: GameID=0 (global) — retrying with console_id={ra_console_id}")
                            continue  # try console-specific query
                        # All queries exhausted — hash genuinely not in RA DB.
                        self._ra_cache[md5u] = None
                        if self.verbose:
                            print(f"      [verbose] RA: GameID=0 (hash not recognised) — falling back to ScreenScraper")
                        return None
                    # GameID found — verify it actually has achievements
                    result = self._ra_game_has_achievements(game_id)
                    self._ra_cache[md5u] = result
                    if result:
                        console_note = f" (arcade console {ra_console_id})" if i > 0 else ""
                        print(f"      [RA] cheevos found (GameID={game_id}){console_note}")
                    elif self.verbose:
                        print(f"      [verbose] RA: GameID={game_id} but 0 achievements")
                    return result
            except Exception as e:
                print(f"      [RA] hash lookup error: {e}")
                break  # don't retry on exception

        # Network/parse error or all queries missed — fall back to ScreenScraper.
        return None

    def run(self):
        print(f"AGSG CCF FE Scraper  v{SCRAPER_VERSION}")
        if self._sftp:
            self._run_sftp()
            return

        systems = sorted(p for p in self.games_dir.iterdir() if p.is_dir())
        if not systems:
            print("No system folders found in Games directory.")
            return

        # RetroAchievements login (if credentials provided)
        if self.ra_user and self.ra_key:
            print(f"RetroAchievements login ({self.ra_user})...", end=" ", flush=True)
            token = self._ra_login()
            if token:
                print("OK ✓")
            else:
                print("FAILED — cheevos detection via RA disabled for this session")

        # Fetch quota upfront so it is visible before the first ROM is processed
        print("Recover ScreenScraper quota...", end=" ", flush=True)
        if self.client.get_user_quota():
            qs = self.client.quota_str()
            print(qs if qs else "OK")
        else:
            print("not available (will be updated upon the first call)")

        # Build merged map: dynamic (all SS systems) with SYSTEM_IDS as curated override
        dynamic_map = build_screenscraper_system_ids(
            self.client.devid, self.client.devpassword)
        system_map = {**dynamic_map, **SYSTEM_IDS}

        total_scraped = 0
        for sys_dir in systems:
            if self.stop_event and self.stop_event.is_set():
                print("\n[!] Scraping interrupted by the user.")
                break
            key = sys_dir.name.lower().strip()
            if self.system_filter and key != self.system_filter:
                continue
            if key in self.folder_overrides:
                system_id = self.folder_overrides[key]
                print(f"\n[{sys_dir.name}]  (forced system → ID: {system_id})")
            else:
                system_id = system_map.get(key)
                if system_id is None:
                    print(f"\n[{sys_dir.name}] — no ScreenScraper mapping, skipping")
                    continue
                print(f"\n[{sys_dir.name}]  (ScreenScraper system ID: {system_id})")
            total_scraped += self._scrape_system(sys_dir, system_id)

        print(f"\n{'='*60}")
        print(f"Total games processed: {total_scraped}")
        qs = self.client.quota_str()
        if qs:
            print(qs)

