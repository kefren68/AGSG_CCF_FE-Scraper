    def _run_sftp(self):
        """Entry point for SSH mode: mirrors remote structure locally, scrapes,
        then uploads all outputs back to the device."""
        staging = Path(tempfile.mkdtemp(prefix="scraper_ssh_"))
        try:
            # Fetch quota first
            print("Recover ScreenScraper quota...", end=" ", flush=True)
            if self.client.get_user_quota():
                qs = self.client.quota_str()
                print(qs if qs else "OK")
            else:
                print("not available (will be updated upon the first call)")

            dynamic_map = build_screenscraper_system_ids(
                self.client.devid, self.client.devpassword)
            system_map = {**dynamic_map, **SYSTEM_IDS}

            system_names = self._sftp.list_subdirs(self._sftp_base)
            if not system_names:
                print(f"No system folders found in remote path: {self._sftp_base}")
                return

            total_scraped = 0
            for sys_name in sorted(system_names):
                if self.stop_event and self.stop_event.is_set():
                    print("\n[!] Scraping interrupted by the user.")
                    break
                key = sys_name.lower().strip()
                if self.system_filter and key != self.system_filter:
                    continue
                if key in self.folder_overrides:
                    system_id = self.folder_overrides[key]
                    print(f"\n[{sys_name}]  (sistema forzato → ID: {system_id})")
                else:
                    system_id = system_map.get(key)
                    if system_id is None:
                        print(f"\n[{sys_name}] — no ScreenScraper mapping, skipping")
                        continue
                    print(f"\n[{sys_name}]  (ScreenScraper system ID: {system_id})")

                local_sys = staging / sys_name
                local_sys.mkdir(parents=True, exist_ok=True)
                remote_sys = self._sftp_base + "/" + sys_name

                self._sftp_sync_in(remote_sys, local_sys)
                n = self._scrape_system(local_sys, system_id)
                total_scraped += n
                if n > 0 or True:  # always sync out to push gamelist.xml
                    self._sftp_sync_out(remote_sys, local_sys)

            print(f"\n{'='*60}")
            print(f"Total games processed: {total_scraped}")
            qs = self.client.quota_str()
            if qs:
                print(qs)
        finally:
            shutil.rmtree(staging, ignore_errors=True)
            self._sftp.close()

    def _sftp_sync_in(self, remote_sys, local_sys):
        """
        Prepare the local staging dir before scraping:
          - Create 0-byte stub files for remote ROMs (so _find_roms can list them)
          - Create 0-byte sentinel files for existing media (so .exists() works)
          - Download .metadata/*.json so cached games can be re-used
        """
        MEDIA_SUBDIRS = list(self.fm.values())
        SKIP_DIRS     = set(MEDIA_SUBDIRS) | {".metadata"}

        # -- ROM stubs --
        all_remote = self._sftp.list_files_recursive(remote_sys)
        for remote_path, size, filename in all_remote:
            rel = remote_path[len(remote_sys):].lstrip("/")
            parts = rel.split("/")
            if parts[0].lower() in SKIP_DIRS:
                continue  # skip media / metadata dirs
            local_file = local_sys / rel
            local_file.parent.mkdir(parents=True, exist_ok=True)
            local_file.touch()  # 0-byte stub — just the filename matters
            self._sftp_sizes[local_file] = size

        # -- Media sentinel files --
        for sub in MEDIA_SUBDIRS:
            remote_sub = remote_sys + "/" + sub
            filenames  = self._sftp.list_files_in_dir(remote_sub)
            if not filenames:
                continue
            local_sub = local_sys / sub
            local_sub.mkdir(exist_ok=True)
            for fn in filenames:
                (local_sub / fn).touch()  # sentinel: marks file as already on device

        # -- Metadata JSON (download so cache is usable) --
        remote_meta = remote_sys + "/.metadata"
        meta_files  = self._sftp.list_files_in_dir(remote_meta)
        if meta_files:
            local_meta = local_sys / ".metadata"
            local_meta.mkdir(exist_ok=True)
            for fn in meta_files:
                if fn.endswith(".json"):
                    try:
                        self._sftp.get(remote_meta + "/" + fn, local_meta / fn)
                    except Exception:
                        pass

    def _sftp_sync_out(self, remote_sys, local_sys):
        """
        Upload scraper outputs from local staging to the remote device.
        Skips 0-byte files (they are sentinels for pre-existing remote files).
        """
        UPLOAD_SUBDIRS = list(self.fm.values()) + [".metadata"]
        items_to_upload = []

        # gamelist.xml
        gl = local_sys / "gamelist.xml"
        if gl.exists() and gl.stat().st_size > 0:
            items_to_upload.append(gl)

        # Media and metadata sub-dirs (skip 0-byte sentinels)
        for sub in UPLOAD_SUBDIRS:
            subdir = local_sys / sub
            if not subdir.is_dir():
                continue
            for f in subdir.iterdir():
                if f.is_file() and f.stat().st_size > 0:
                    items_to_upload.append(f)

        for local_file in items_to_upload:
            rel = local_file.relative_to(local_sys).as_posix()
            remote_dest = remote_sys + "/" + rel
            try:
                self._sftp.put(str(local_file), remote_dest)
                if self.verbose:
                    print(f"  [SSH] uploaded {rel}", file=sys.stderr)
            except Exception as e:
                print(f"  [!] SSH upload failed for {rel}: {e}", file=sys.stderr)

