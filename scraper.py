def crc32_of_file(path):
    """Return CRC32 as 8-char uppercase hex string (ScreenScraper romcrc format)."""
    crc = 0
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            crc = zlib.crc32(chunk, crc)
    return f"{crc & 0xFFFFFFFF:08X}"

def _md5_of_file(path):
    """Return MD5 hex digest of a whole file (used for arcade ZIPs)."""
    h = hashlib.md5()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()

