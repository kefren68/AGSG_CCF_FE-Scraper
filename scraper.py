def _ra_rom_md5(rom_path, system_id=None):
    """Compute the rcheevos-compatible MD5 hash used by RetroAchievements.

    RetroArch uses rcheevos (rc_hash.c) which applies system-specific
    pre-processing before computing MD5.  A plain file MD5 only matches for
    systems that need no pre-processing; for others the hash won't be found in
    the RA database even though the game has achievements.

    Pass system_id (ScreenScraper system ID) so that arcade systems (Neo Geo,
    CPS1/2/3) are hashed as MD5 of the filename stem, matching what rcheevos
    does via rc_hash_arcade() for the FBNeo core.

    Returns None for disc-image formats and on any error — the caller then
    falls back to ScreenScraper's retroachievement field.

    Pre-processing rules (from rcheevos rc_hash.c):
    ┌──────────────────────────────┬─────────────────────────────────────────────┐
    │ System / extension           │ Rule                                        │
    ├──────────────────────────────┼─────────────────────────────────────────────┤
    │ NES          (.nes)          │ Strip 16-byte iNES header if magic NES\\x1a │
    │ SNES         (.sfc/.smc/.fig)│ Strip 512-byte copier header if             │
    │                              │   filesize % 1024 == 512                    │
    │ PC Engine    (.pce/.sgx)     │ Same 512-byte rule as SNES                  │
    │ Atari 7800   (.a78)          │ Strip 128-byte A78 header                   │
    │                              │   (byte 0 == 0x01, bytes 1-9 == "ATARI7800")│
    │ Atari Lynx   (.lnx)          │ Strip 64-byte LNX header (magic b"LYNX")    │
    │ N64          (.v64)          │ Word-swap all bytes (→ big-endian)          │
    │ N64          (.n64)          │ 4-byte group reverse (→ big-endian)         │
    │ NDS          (.nds)          │ MD5(header[0:0x160] + ARM9 binary)          │
    │ Sega MD      (.smd)          │ Skip 512-byte header, deinterleave 16KB blks│
    │ Everything else              │ Plain MD5 of (decompressed) content         │
    │   (GB/GBC/GBA, MD .md/.gen,  │                                             │
    │    SMS/GG, A2600/5200, CV,   │                                             │
    │    Intv, NGP, WS, VB, …)    │                                             │
    └──────────────────────────────┴─────────────────────────────────────────────┘
    """
    suffix = rom_path.suffix.lower()
    try:
        if suffix == ".zip":
            # Arcade systems (CPS1/2/3, Neo Geo): rcheevos rc_hash_arcade()
            # hashes the ROM *filename* (without extension) as a byte string —
            # NOT the ZIP contents and NOT the whole file.
            # e.g.  sf2.zip  →  MD5("sf2")
            # Source: rcheevos/src/rhash/hash.c  rc_hash_arcade()
            if system_id in _RA_ARCADE_SYSTEM_IDS:
                stem = rom_path.stem  # filename without .zip
                return hashlib.md5(stem.encode("ascii", errors="replace")).hexdigest()
            with zipfile.ZipFile(rom_path, "r") as zf:
                members = [m for m in zf.infolist() if not m.is_dir()]
                if not members:
                    return None
                entry = max(members, key=lambda m: m.file_size)
                inner_suffix = Path(entry.filename).suffix.lower()
                if inner_suffix in _RA_CD_FORMATS:
                    return None  # disc image inside zip — can't hash correctly
                with zf.open(entry) as f:
                    data = f.read()
        else:
            if suffix in _RA_CD_FORMATS:
                return None  # disc image — fall back to ScreenScraper field
            inner_suffix = suffix
            with open(rom_path, "rb") as f:
                data = f.read()
    except Exception:
        return None

    # ------------------------------------------------------------------
    # rcheevos-compatible pre-processing (rc_hash.c)
    # ------------------------------------------------------------------

    if inner_suffix == ".nes":
        # iNES / NES 2.0 header: 16 bytes starting with "NES\x1a"
        if data[:4] == b"NES\x1a" and len(data) > 16:
            data = data[16:]

    elif inner_suffix in (".sfc", ".smc", ".fig"):
        # SNES: 512-byte copier header present when filesize % 1024 == 512
        if len(data) % 1024 == 512:
            data = data[512:]

    elif inner_suffix in (".pce", ".sgx"):
        # PC Engine / SuperGrafx: same 512-byte copier header rule as SNES
        if len(data) % 1024 == 512:
            data = data[512:]

    elif inner_suffix == ".a78":
        # Atari 7800: 128-byte A78 header → byte 0 == 0x01, bytes 1-9 == "ATARI7800"
        if len(data) > 128 and data[0:1] == b"\x01" and data[1:10] == b"ATARI7800":
            data = data[128:]

    elif inner_suffix == ".lnx":
        # Atari Lynx: 64-byte LNX header starting with "LYNX"
        if len(data) > 64 and data[:4] == b"LYNX":
            data = data[64:]

    elif inner_suffix == ".v64":
        # N64 word-swapped (V64 / Doctor V64): swap every pair of bytes → big-endian
        arr = bytearray(data)
        arr[0::2], arr[1::2] = bytearray(arr[1::2]), bytearray(arr[0::2])
        data = bytes(arr)

    elif inner_suffix == ".n64":
        # N64 little-endian (N64 / Mr. Backup Z64): reverse each 4-byte group → big-endian
        arr = bytearray(data)
        for i in range(0, len(arr) - 3, 4):
            arr[i], arr[i+1], arr[i+2], arr[i+3] = arr[i+3], arr[i+2], arr[i+1], arr[i]
        data = bytes(arr)

    elif inner_suffix == ".nds":
        # Nintendo DS: MD5 of ROM header (0x160 bytes) + ARM9 binary.
        # ARM9 ROM offset at bytes 0x20-0x23, ARM9 size at 0x2C-0x2F (little-endian).
        if len(data) < 0x160:
            return None
        arm9_offset = struct.unpack_from("<I", data, 0x20)[0]
        arm9_size   = struct.unpack_from("<I", data, 0x2C)[0]
        header = data[:0x160]
        arm9_end = arm9_offset + arm9_size
        arm9 = data[arm9_offset:arm9_end] if (arm9_size > 0 and arm9_end <= len(data)) else b""
        return hashlib.md5(header + arm9).hexdigest()

    elif inner_suffix == ".smd":
        # Sega Mega Drive interleaved dump (Super Magic Drive format).
        # 512-byte SMD header is skipped, then ROM data is stored in 16 KB blocks
        # where odd ROM bytes occupy the first 8 KB and even ROM bytes the second 8 KB.
        if len(data) <= 512:
            return None
        rom = data[512:]        # skip 512-byte SMD header
        out = bytearray()
        HALF = 0x2000           # 8 KB
        BLOCK = HALF * 2        # 16 KB
        for blk_start in range(0, len(rom), BLOCK):
            block = rom[blk_start:blk_start + BLOCK]
            half  = len(block) // 2
            for i in range(half):
                out.append(block[half + i])  # even ROM byte (low)
                out.append(block[i])          # odd  ROM byte (high)
        data = bytes(out)

    # All other systems use plain MD5:
    #   Game Boy / GBC / GBA, Sega MD (.md/.gen), Master System, Game Gear,
    #   Atari 2600/5200 (.bin/.a26/.a52), ColecoVision, Intellivision,
    #   Neo Geo Pocket, WonderSwan, Virtual Boy, Vectrex, SG-1000, 32X,
    #   MSX ROMs, Arduboy, Magnavox Odyssey 2, Fairchild Channel F, …
    return hashlib.md5(data).hexdigest()


def _rom_hashes(rom_path):
    """Return (crc32_hex, md5_hex, inner_name, size) for a ROM file.

    For .zip archives, hashes and name refer to the largest file inside
    (the actual ROM), since ScreenScraper indexes the uncompressed content.
    For plain files, hashes are computed directly on the file.
    """
    suffix = rom_path.suffix.lower()
    if suffix == ".zip":
        try:
            with zipfile.ZipFile(rom_path, "r") as zf:
                # Pick the largest member (most likely the ROM, not a readme/nfo)
                members = [m for m in zf.infolist() if not m.is_dir()]
                if not members:
                    raise ValueError("empty zip")
                entry = max(members, key=lambda m: m.file_size)
                # CRC32 is stored uncompressed in the zip central directory
                crc_hex = f"{entry.CRC & 0xFFFFFFFF:08X}"
                # MD5 requires reading the decompressed content
                h = hashlib.md5()
                with zf.open(entry) as f:
                    while True:
                        chunk = f.read(65536)
                        if not chunk:
                            break
                        h.update(chunk)
                return crc_hex, h.hexdigest(), entry.filename, entry.file_size
        except Exception:
            pass  # fall through to plain-file hashing
    # Plain file (or failed zip)
    h = hashlib.md5()
    crc = 0
    size = rom_path.stat().st_size
    with open(rom_path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            h.update(chunk)
            crc = zlib.crc32(chunk, crc)
    return f"{crc & 0xFFFFFFFF:08X}", h.hexdigest(), rom_path.name, size


def pick_region(items, tag_key, preferred, text_key="text", fallback=None):
    """
    Pick the best value from a list of region/language-tagged dicts.
    Tries preferred → fallback → 'wor' → first available.
    """
    # ScreenScraper's PHP API sometimes returns a single item as a dict instead of a list
    if isinstance(items, dict):
        items = [items]
    if not items:
        return None
    for item in items:
        if item.get(tag_key, "").lower() == preferred.lower():
            return item.get(text_key)
    if fallback and fallback.lower() != preferred.lower():
        for item in items:
            if item.get(tag_key, "").lower() == fallback.lower():
                return item.get(text_key)
    for item in items:
        if item.get(tag_key, "").lower() == "wor":
            return item.get(text_key)
    return items[0].get(text_key)


